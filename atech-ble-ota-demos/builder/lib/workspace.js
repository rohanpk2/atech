'use strict';

// Isolated PlatformIO workspace per demo. The checked-in demo project is the
// source of truth for the protected core; the workspace receives a fresh copy
// of it plus the generated app for every job, and is never uploaded over USB.
const fs = require('node:fs');
const fsp = require('node:fs/promises');
const path = require('node:path');
const {loadConfig} = require('./config');
const {runPio, parseDiagnostics} = require('./pio');

const AI_ENV_BLOCK = '\n; AI firmware builder target (added by the backend).\n[env:ai]\n' +
                     'build_flags = ${env.build_flags} -DDEMO_VERSION=3 -DATECH_AI_BUILD=1\n';
const GENERATED_FILES = new Set(['user_app.cpp', 'app_build.h']);

function rewritePlatformioIni(ini, {sharedDir, cacheDir}) {
  let out = String(ini);
  if (/^lib_extra_dirs\s*=/m.test(out)) {
    out = out.replace(/^lib_extra_dirs\s*=.*$/m, `lib_extra_dirs = ${sharedDir}`);
  } else {
    out = out.replace(/^\[env\]\s*$/m, `[env]\nlib_extra_dirs = ${sharedDir}`);
  }
  if (/^build_cache_dir\s*=/m.test(out)) {
    out = out.replace(/^build_cache_dir\s*=.*$/m, `build_cache_dir = ${cacheDir}`);
  } else {
    out = out.replace(/^\[env\]\s*$/m, `[env]\nbuild_cache_dir = ${cacheDir}`);
  }
  if (!/^\[env:ai\]/m.test(out)) out = out.trimEnd() + '\n' + AI_ENV_BLOCK;
  return out;
}

function cEscape(text) {
  return String(text ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r?\n/g, '\\n')
    .replace(/[^\x20-\x7e]/g, '');
}

function renderAppBuildHeader({buildId, appName, appVersion, targetDeviceId}) {
  const version = Number.isInteger(Number(appVersion)) && Number(appVersion) > 0 ? Number(appVersion) : 3;
  return [
    `// Generated by the Atech AI firmware builder for build ${cEscape(buildId)}. Do not edit.`,
    '#pragma once',
    `#define ATECH_BUILD_ID "${cEscape(buildId)}"`,
    `#define ATECH_APP_NAME "${cEscape(appName)}"`,
    `#define ATECH_APP_VERSION ${version}`,
    `#define ATECH_TARGET_DEVICE_ID "${cEscape(targetDeviceId)}"`,
    '',
  ].join('\n');
}

function workspaceDir(config, demo) {
  return path.join(config.buildsDir, 'workspaces', `demo${demo}`);
}

async function prepareWorkspace(demo, {code, meta}, {config = loadConfig()} = {}) {
  const entry = config.demos[demo];
  if (!entry) throw new Error(`Unknown demo ${demo}`);
  const dir = workspaceDir(config, demo);
  const srcDir = path.join(dir, 'src');
  await fsp.mkdir(path.join(srcDir, 'app'), {recursive: true});

  const ini = await fsp.readFile(path.join(entry.dir, 'platformio.ini'), 'utf8');
  await fsp.writeFile(path.join(dir, 'platformio.ini'),
                      rewritePlatformioIni(ini, {sharedDir: config.sharedDir,
                                                 cacheDir: path.join(config.buildsDir, 'cache')}));
  await fsp.copyFile(path.join(entry.dir, 'partitions.csv'), path.join(dir, 'partitions.csv'));
  await fsp.cp(path.join(entry.dir, 'src'), srcDir, {
    recursive: true, force: true,
    filter: source => !GENERATED_FILES.has(path.basename(source)),
  });
  await fsp.writeFile(path.join(srcDir, 'app', 'user_app.cpp'), code);
  await fsp.writeFile(path.join(srcDir, 'app', 'app_build.h'), renderAppBuildHeader(meta));
  return {dir};
}

async function compileWorkspace(demo, dir, {config = loadConfig(), onLine, timeoutMs = 900000} = {}) {
  const firmwarePath = path.join(dir, '.pio', 'build', 'ai', 'firmware.bin');
  // Never let a previous job's artifact survive a failed link.
  await fsp.rm(firmwarePath, {force: true});
  const result = await runPio(['run', '-e', 'ai'], {cwd: dir, onLine, timeoutMs, pioBin: config.pio});
  const diagnostics = parseDiagnostics(result.log);
  const ok = result.code === 0 && fs.existsSync(firmwarePath);
  return {ok, code: result.code, timedOut: result.timedOut, log: result.log, diagnostics,
          firmwarePath: ok ? firmwarePath : null};
}

module.exports = {rewritePlatformioIni, renderAppBuildHeader, prepareWorkspace, compileWorkspace, workspaceDir};
