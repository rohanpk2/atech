#!/usr/bin/env node
// Build step for the Vercel project. Assembles dist/ from the unchanged dashboards and shared
// modules one directory up, writes the hosted runtime configuration, and refuses to produce an
// output that would be broken (missing Vercel environment) or unsafe (a secret value copied in).
//
//   dist/demo1/   <- ../demo1-custom-gatt/web
//   dist/demo2/   <- ../demo2-bleota-library/web
//   dist/shared/  <- ../web-shared, then shared/atech-config.js replaced by the hosted config
//
// Nothing here reads ATECH_BUILDER_KEY for any purpose other than making sure it is set and
// absent from the output: Vercel injects it into proxied /api requests at request time.
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const SOURCES = [['demo1-custom-gatt/web', 'demo1'], ['demo2-bleota-library/web', 'demo2'], ['web-shared', 'shared']];
const HOSTED_CONFIG = {apiBase: '', transport: 'poll', hosted: true, pollMs: 3000};
const BACKEND_URL = /^https:\/\/[A-Za-z0-9.-]+(:[0-9]+)?$/;
const REQUIRED = ['ATECH_BUILDER_KEY', 'ATECH_DASHBOARD_USER'];
const SECRET_VARS = ['ATECH_BUILDER_KEY', 'ANTHROPIC_API_KEY'];
const MIN_SECRET_SCAN_LENGTH = 8;   // shorter values would match ordinary text by accident

// Problems with the Vercel environment, one line each; empty when everything needed is there.
export function validateEnv(env = {}) {
  const problems = [];
  const url = env.ATECH_BACKEND_URL;
  if (!url) problems.push('ATECH_BACKEND_URL is not set (the backend origin, for example https://atech-api.example.com)');
  else if (!BACKEND_URL.test(url)) problems.push(`ATECH_BACKEND_URL must be https://<host>[:port] with no path or trailing slash, got "${url}"`);
  for (const name of REQUIRED) if (!env[name]) problems.push(`${name} is not set`);
  return problems;
}

export function hostedConfigSource() {
  return '// Generated by vercel-frontend/build.js for the hosted dashboards: same-origin API through\n' +
         '// Vercel, progress by polling (no EventSource), copy written for a cloud build service.\n' +
         `window.ATECH_CONFIG = ${JSON.stringify(HOSTED_CONFIG)};\n`;
}

function skip(name) {
  return name.startsWith('.') || name.endsWith('.test.js') || name === 'node_modules';
}

async function copyTree(src, dest, prefix, files) {
  await fs.mkdir(dest, {recursive: true});
  for (const entry of await fs.readdir(src, {withFileTypes: true})) {
    if (skip(entry.name)) continue;
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    const rel = path.posix.join(prefix, entry.name);
    if (entry.isDirectory()) await copyTree(from, to, rel, files);
    else if (entry.isFile()) { await fs.copyFile(from, to); files.push(rel); }
  }
}

async function scanForSecrets(outDir, files, env) {
  const values = SECRET_VARS.map(name => env[name]).filter(v => typeof v === 'string' && v.length >= MIN_SECRET_SCAN_LENGTH);
  if (!values.length) return;
  for (const rel of files) {
    const text = await fs.readFile(path.join(outDir, rel), 'utf8');
    if (values.some(value => text.includes(value))) throw new Error(`Secret value found in build output: ${rel}`);
  }
}

// Returns {files}: the output paths relative to outDir, sorted.
export async function assembleDist({rootDir, outDir, env = process.env, allowMissingEnv = false}) {
  const problems = validateEnv(env);
  if (problems.length && !allowMissingEnv) {
    throw new Error(`The Vercel environment is incomplete; set these project environment variables and redeploy:\n  - ${problems.join('\n  - ')}`);
  }
  const root = path.resolve(rootDir);
  const out = path.resolve(outDir);
  if (out === root || root.startsWith(out + path.sep) || out === path.parse(out).root) throw new Error(`Refusing to clear ${out}`);
  await fs.rm(out, {recursive: true, force: true});
  await fs.mkdir(out, {recursive: true});
  const files = [];
  for (const [from, to] of SOURCES) await copyTree(path.join(root, from), path.join(out, to), to, files);
  await fs.writeFile(path.join(out, 'shared', 'atech-config.js'), hostedConfigSource());
  if (!files.includes('shared/atech-config.js')) files.push('shared/atech-config.js');
  await scanForSecrets(out, files, env);
  return {files: files.sort()};
}

async function main() {
  const allowMissingEnv = process.env.ATECH_ALLOW_MISSING_ENV === '1' || process.argv.includes('--allow-missing-env');
  const outDir = path.join(here, 'dist');
  try {
    const {files} = await assembleDist({rootDir: path.resolve(here, '..'), outDir, env: process.env, allowMissingEnv});
    console.log(`vercel-frontend: wrote ${files.length} files to ${outDir}`);
  } catch (error) {
    console.error(`vercel-frontend build failed: ${error.message}`);
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
